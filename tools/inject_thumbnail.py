#!/usr/bin/env python3
"""
Bettet ein gerendertes Vorschaubild als PNG-Thumbnail ins Gcode ein, damit das
MK4S-Display + PrusaLink zeigen, WAS gedruckt wird. Noetig, weil headless CLI-Slicing
kein Thumbnail rendert (kein OpenGL-Kontext).

Usage: inject_thumbnail.py <modell.stl> <datei.gcode> [WxH]
Schreibt datei.gcode in-place (Thumbnail-Block direkt nach dem Header).
"""
import sys, base64, io, numpy as np, trimesh, matplotlib
matplotlib.use('Agg'); import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d.art3d import Poly3DCollection
import matplotlib.cm as cm

stl, gco = sys.argv[1], sys.argv[2]
W,H = (map(int,sys.argv[3].split('x')) if len(sys.argv)>3 else (440,240)); W,H=int(W),int(H)

m=trimesh.load(stl)
tris=np.asarray(m.vertices[m.faces]); fc=tris.mean(1); n=np.asarray(m.face_normals)
sh=np.clip(n@np.array([-0.3,-0.5,0.8]),0.2,1)
col=cm.gist_earth((fc[:,2]-m.bounds[0][2])/(np.ptp(m.vertices[:,2])+1e-9)); col[:,:3]*=sh[:,None]
fig=plt.figure(figsize=(W/100,H/100),dpi=100); ax=fig.add_subplot(111,projection='3d')
ax.add_collection3d(Poly3DCollection(tris,facecolors=col,edgecolors='none'))
mx=max(m.extents[:2]); ax.set_xlim(0,mx);ax.set_ylim(0,mx);ax.set_zlim(0,mx)
ax.set_box_aspect((1,1,1)); ax.view_init(elev=22,azim=-62); ax.set_axis_off()
buf=io.BytesIO(); plt.savefig(buf,format='png',dpi=100,bbox_inches='tight',pad_inches=0,
    facecolor='black'); plt.close(); png=buf.getvalue()

b64=base64.b64encode(png).decode()
block=[f"; thumbnail begin {W}x{H} {len(b64)}"]
block += ["; "+b64[i:i+76] for i in range(0,len(b64),76)]
block += ["; thumbnail end", ""]
thumb="\n".join(block)+"\n"

src=open(gco).read().splitlines(keepends=True)
# nach der ersten echten Zeile (; generated by ...) einfuegen
out=[]; done=False
for ln in src:
    out.append(ln)
    if not done and ln.startswith("; generated by"):
        out.append("\n"+thumb); done=True
if not done: out.insert(0, thumb)   # fallback: ganz vorne
open(gco,"w").write("".join(out))
print(f"Thumbnail {W}x{H} ({len(png)} B PNG) eingebettet in {gco}")
